import assert from 'node:assert/strict';
import { appendFile, readFile, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';

export async function checkSessionPreviews({ page, sessions, artifacts, waitForSnapshot }) {
  const id = 'codex:codex:fixture-root';
  const childId = 'codex:codex:fixture-child';
  const preview = value => page.locator(`[data-preview-session-id="${value}"]`);
  const node = value => page.locator(`[data-session-id="${value}"]`);
  const menuItem = () => page.getByRole('menuitem', { name: 'Podgląd sesji', exact: true });
  const resize = async (window, edge, dx, dy) => {
    const handle = await window.getByTestId(`preview-resize-${edge}`).boundingBox();
    assert.ok(handle);
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2); await page.mouse.down();
    await page.mouse.move(handle.x + handle.width / 2 + dx, handle.y + handle.height / 2 + dy, { steps: 8 }); await page.mouse.up();
    return window.boundingBox();
  };
  const open = async value => {
    const rect = await node(value).boundingBox();
    assert.ok(rect);
    await node(value).dispatchEvent('contextmenu', { button: 2, clientX: rect.x + rect.width / 2, clientY: rect.y + rect.height / 2 });
    await menuItem().click();
    await preview(value).waitFor();
  };
  await node(id).click({ button: 'right' });
  await menuItem().waitFor();
  assert.equal(await page.getByTestId('details-panel').count(), 0, 'right click does not select a details panel');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('menu').count(), 0);
  await page.locator('.react-flow__node').filter({ has: node(id) }).focus();
  await page.keyboard.press('Shift+F10');
  await menuItem().waitFor();
  await menuItem().click();
  const root = preview(id);
  await root.getByText('CODEX_PREVIEW_fixture-root', { exact: true }).waitFor();
  await root.getByText('<b>CODEX_RESULT_fixture-root</b>', { exact: true }).waitFor();
  assert.equal(await root.locator('b,img,script').count(), 0, 'log contents are plain text');
  assert.equal(await root.getByRole('checkbox', { name: 'Śledź nowe zdarzenia' }).isChecked(), true);
  const graphTransform = await page.locator('.react-flow__viewport').getAttribute('style');
  const before = await root.boundingBox();
  const handle = await root.getByTestId('preview-drag-handle').boundingBox();
  await page.mouse.move(handle.x + 100, handle.y + 20); await page.mouse.down();
  await page.mouse.move(handle.x + 180, handle.y + 35, { steps: 8 }); await page.mouse.up();
  const moved = await root.boundingBox();
  assert.ok(moved.x - before.x >= 50, 'dragging the title moves the floating window');
  assert.equal(await page.locator('.react-flow__viewport').getAttribute('style'), graphTransform, 'dragging a preview never pans the graph');
  await root.getByTestId('preview-drag-handle').focus();
  await page.keyboard.press('ArrowLeft');
  assert.ok(Math.abs((await root.boundingBox()).x - (moved.x - 10)) < 1, 'keyboard movement is available');
  const originalSize = await root.boundingBox();
  const larger = await resize(root, 'se', 60, 25);
  assert.ok(Math.abs(larger.width - originalSize.width - 60) < 1 && Math.abs(larger.height - originalSize.height - 25) < 1, 'corner dragging changes both dimensions');
  assert.ok(Math.abs(larger.x - originalSize.x) < 1 && Math.abs(larger.y - originalSize.y) < 1, 'southeast resizing keeps the upper left corner fixed');
  await resize(root, 'e', -400, 0);
  await resize(root, 's', 0, -250);
  const minimum = await root.boundingBox();
  assert.equal(minimum.width, 320); assert.equal(minimum.height, 240);
  const west = await resize(root, 'w', -40, 0);
  assert.ok(Math.abs(west.width - minimum.width - 40) < 1 && Math.abs(west.x + west.width - minimum.x - minimum.width) < 1, 'left edge keeps the right edge fixed');
  const north = await resize(root, 'n', 0, -10);
  assert.ok(Math.abs(north.height - west.height - 10) < 1 && Math.abs(north.y + north.height - west.y - west.height) < 1, 'top edge keeps the bottom edge fixed');
  await root.getByTestId('preview-resize-se').focus();
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowDown');
  const customSize = await root.boundingBox();
  assert.equal(customSize.width, north.width + 10); assert.equal(customSize.height, north.height + 10);
  assert.equal(await page.locator('.react-flow__viewport').getAttribute('style'), graphTransform, 'resizing a preview never pans or zooms the graph');
  const event = text => JSON.stringify({ type: 'response_item', timestamp: new Date().toISOString(), payload: { type: 'function_call_output', output: text } }) + '\n';
  await appendFile(path.join(sessions, 'rollout-fixture-root.jsonl'), event('PREVIEW_LIVE_UPDATE\n' + Array.from({ length: 30 }, (_, i) => `output line ${i}`).join('\n')));
  await root.getByText(/PREVIEW_LIVE_UPDATE/).waitFor();
  assert.ok(await root.getByTestId('preview-events').evaluate(element => element.scrollHeight - element.clientHeight - element.scrollTop < 5), 'follow scrolls to new output');
  const scrollArea = await root.getByTestId('preview-events').boundingBox();
  assert.equal(await page.evaluate(({ x, y }) => !!document.elementFromPoint(x, y)?.closest('.preview-resize-handle'), { x: scrollArea.x + scrollArea.width - 2, y: scrollArea.y + scrollArea.height / 2 }), false, 'the resize edge leaves the scrollbar reachable');
  await root.getByRole('checkbox', { name: 'Śledź nowe zdarzenia' }).uncheck();
  await root.getByTestId('preview-events').evaluate(element => { element.scrollTop = 0; });
  await appendFile(path.join(sessions, 'rollout-fixture-root.jsonl'), event('PREVIEW_SECOND_UPDATE'));
  await root.getByText('PREVIEW_SECOND_UPDATE', { exact: true }).waitFor();
  assert.equal(await root.getByTestId('preview-events').evaluate(element => element.scrollTop), 0, 'follow can be paused to read earlier events');
  assert.equal((await root.boundingBox()).width, customSize.width, 'polling keeps the chosen width');
  assert.equal((await root.boundingBox()).height, customSize.height, 'polling keeps the chosen height');
  await open(childId);
  const child = preview(childId);
  await child.getByText('CODEX_PREVIEW_fixture-child', { exact: true }).waitFor();
  assert.doesNotMatch(await child.innerText(), /CODEX_PREVIEW_fixture-root|PREVIEW_LIVE_UPDATE/);
  assert.equal(await page.getByTestId('session-preview').count(), 2, 'multiple agents can be observed independently');
  assert.equal((await child.boundingBox()).width, 560, 'each preview has an independent size');
  await open(id);
  assert.equal(await page.getByTestId('session-preview').count(), 2, 'reopening a session raises its existing window');
  assert.equal((await root.boundingBox()).width, customSize.width, 'raising an existing preview preserves its size');
  await root.getByRole('button', { name: /^Zamknij podgląd/ }).click();
  assert.equal(await page.getByTestId('session-preview').count(), 1);
  const file = path.join(sessions, 'rollout-fixture-child.jsonl');
  const saved = await readFile(file, 'utf8');
  try {
    await unlink(file);
    await waitForSnapshot(snapshot => !snapshot.sessions.some(session => session.id === childId));
    await child.locator('.preview-error').waitFor();
    assert.match(await child.innerText(), /dane mogą być nieaktualne/);
  } finally { await writeFile(file, saved); }
  await waitForSnapshot(snapshot => snapshot.sessions.some(session => session.id === childId));
  await child.locator('.preview-error').waitFor({ state: 'hidden' });
  await page.getByTestId('runtime-filter').selectOption('claude-code');
  assert.equal(await child.isVisible(), true, 'filtering the graph preserves open windows');
  await child.getByRole('button', { name: /^Zamknij podgląd/ }).click();
  const claudeId = 'claude-code:claude-code:fixture-root';
  await open(claudeId);
  const claude = preview(claudeId);
  await claude.getByText('CLAUDE_PREVIEW_root', { exact: true }).waitFor();
  assert.match(await claude.innerText(), /Bash/);
  assert.doesNotMatch(await claude.innerText(), /CODEX_PREVIEW/);
  await page.screenshot({ path: path.join(artifacts, 'session-preview-claude.png') });
  await claude.getByRole('button', { name: /^Zamknij podgląd/ }).click();
  await page.getByTestId('runtime-filter').selectOption('gemini-cli');
  const geminiId = 'gemini-cli:gemini-cli:fixture-root';
  await open(geminiId);
  const gemini = preview(geminiId);
  await gemini.getByText('GEMINI_PREVIEW_root', { exact: true }).waitFor();
  await gemini.getByText('GEMINI_RESULT_root', { exact: true }).waitFor();
  const preferred = await resize(gemini, 'se', 60, 20);
  await page.setViewportSize({ width: 1080, height: 740 });
  await page.waitForTimeout(250);
  const bounds = await page.locator('.graph-body').boundingBox(), window = await gemini.boundingBox();
  assert.ok(window.x >= bounds.x && window.y >= bounds.y && window.x + window.width <= bounds.x + bounds.width + 1 && window.y + window.height <= bounds.y + bounds.height + 1, 'window and close button remain inside the graph after resizing');
  assert.equal(await gemini.getByRole('button', { name: /^Zamknij podgląd/ }).isVisible(), true);
  await page.setViewportSize({ width: 1510, height: 940 });
  await page.waitForTimeout(250);
  assert.equal((await gemini.boundingBox()).width, preferred.width, 'expanding the application restores the preferred width');
  assert.equal((await gemini.boundingBox()).height, preferred.height, 'expanding the application restores the preferred height');
  await gemini.getByTestId('preview-drag-handle').focus();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByTestId('session-preview').count(), 0);
  await page.setViewportSize({ width: 1510, height: 940 });
  // Let ResizeObserver and the scheduled fit animation finish before a new context-menu gesture.
  await page.waitForTimeout(450);
  await page.getByTestId('runtime-filter').selectOption('codex');
  await open(id);
  await preview(id).getByText('CODEX_PREVIEW_fixture-root', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(artifacts, 'session-preview-codex.png') });
  await preview(id).getByRole('button', { name: /^Zamknij podgląd/ }).click();
  assert.equal(await page.evaluate(async () => {
    try { await window.monitor.getSessionPreview('../../etc/passwd'); return false; } catch { return true; }
  }), true, 'preview IPC rejects unknown IDs and arbitrary paths');
  assert.equal(await page.evaluate(async () => JSON.stringify(await window.monitor.getSnapshot()).includes('CODEX_PREVIEW')), false, 'raw activity is excluded from regular graph snapshots');
  await page.getByTestId('runtime-filter').selectOption('all');
  console.log('PASS: Agent context menu and keyboard access, independent movable/resizable previews, edge/corner/keyboard resizing, minimum sizes and viewport bounds, preferred-size restoration, live log updates, follow/pause, source isolation, stale/recovery states and close controls.');
}
